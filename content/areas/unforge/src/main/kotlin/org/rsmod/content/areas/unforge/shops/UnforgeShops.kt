/**
 * Multi-shop shopkeeper dialogues.
 *
 * Single-shop npcs are no longer registered here: they carry [ShopParams.npc_shop] /
 * [ShopParams.npc_shop_title] via [UnforgeShopEdits] and are bound generically by npc type,
 * independent of spawn coordinates. The three vendors below offer a shop choice menu instead, so
 * they keep an explicit op handler - but also coord-free.
 */
class UnforgeShops @Inject constructor(private val shops: Shops) : PluginScript() {
    override fun ScriptContext.startup() {
        onOpNpc1(UnforgeShopNpcs.gunnjorn) { gunnjornMenu(it.npc) }
        onOpNpc1(UnforgeShopNpcs.route_radigad_ponfit) { radigadMenu(it.npc) }
        onOpNpc1(UnforgeShopNpcs.traiborn) { traibornMenu(it.npc) }
    }

    private suspend fun ProtectedAccess.gunnjornMenu(npc: Npc) {
        startDialogue(npc) {
            val sel =
                choice3(
                    "Melee",
                    "Melee Shop" to UnforgeShopInvRefs.cw_melee_shop,
                    "Armour",
                    "Melee Armour Shop" to UnforgeShopInvRefs.cw_melee_armour,
                    "Ironman",
                    "Ironman Melee Shop" to UnforgeShopInvRefs.cw_melee_ironman,
                )
            shops.open(player, npc, sel.first, sel.second)
        }
    }

    private suspend fun ProtectedAccess.radigadMenu(npc: Npc) {
        startDialogue(npc) {
            val sel =
                choice3(
                    "Ranged",
                    "Ranged Weapons & Ammo Shop" to
                        UnforgeShopInvRefs.cw_ranged_ammo_and_weapons_shop,
                    "Armour",
                    "Ranged Armour Shop" to UnforgeShopInvRefs.cw_ranged_armour_shop,
                    "Ironman",
                    "Ironman Ranged Shop" to UnforgeShopInvRefs.cw_ranged_ironman,
                )
            shops.open(player, npc, sel.first, sel.second)
        }
    }

    private suspend fun ProtectedAccess.traibornMenu(npc: Npc) {
        startDialogue(npc) {
            val sel =
                choice3(
                    "Magic",
                    "Magic Shop" to UnforgeShopInvRefs.cw_magic_shop,
                    "Armour",
                    "Magic Armor Shop" to UnforgeShopInvRefs.cw_magic_armor,
                    "Ironman",
                    "Ironman Magic Shop" to UnforgeShopInvRefs.cw_magic_ironman,
                )
            shops.open(player, npc, sel.first, sel.second)
        }
    }
}
